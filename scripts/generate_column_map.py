# scripts/generate_column_map.py

import sys
import os
import json
import re

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from src.core.database.connection import DatabaseConnection
from src.core.llm.client import LLMClient
from src.utils.config_loader import load_config


def get_all_columns(db_conn):
    """
    Fetch all column names from Orders, OrderItems, and Shipments tables.
    """
    cursor = db_conn.cursor()
    cursor.execute("""
        SELECT 
            TABLE_NAME,
            COLUMN_NAME
        FROM INFORMATION_SCHEMA.COLUMNS
        WHERE TABLE_SCHEMA = 'Sale'
          AND TABLE_NAME IN ('Orders', 'OrderItems', 'Shipments')
        ORDER BY TABLE_NAME, ORDINAL_POSITION
    """)
    rows = cursor.fetchall()

    columns = []
    for row in rows:
        columns.append({
            "table": row[0],
            "column": row[1]
        })
    return columns


def translate_chunk(chunk, llm_client, chunk_index, total_chunks):
    """
    Translate a chunk of column names (max 15 items per chunk).
    """
    column_list_str = "\n".join(chunk)
    total_count = len(chunk)

    prompt = f"""You are a translator. Translate the following English column names from a SQL Server database into Persian (Farsi).

**IMPORTANT RULES:**
1. You MUST translate ALL {total_count} column names listed below.
2. Return ONLY a valid JSON object with the original column names as keys and their Persian translations as values.
3. The JSON must have EXACTLY {total_count} key-value pairs.
4. Do NOT add any extra text, explanation, or formatting outside the JSON.
5. Use proper Persian terms (e.g., "Id" -> "شناسه", "buyer" -> "خریدار", "quantity" -> "تعداد").
6. If a column name is already Persian or cannot be translated, keep it as is.

Column names to translate (chunk {chunk_index + 1} of {total_chunks}):
{column_list_str}

JSON output (with exactly {total_count} items):"""

    response = llm_client.generate(prompt)

    json_match = re.search(r'\{.*\}', response, re.DOTALL)
    if not json_match:
        raise ValueError(f"Could not extract JSON from LLM response for chunk {chunk_index + 1}")

    json_str = json_match.group(0)
    try:
        translation_map = json.loads(json_str)
        return translation_map
    except json.JSONDecodeError as e:
        raise ValueError(f"Invalid JSON from LLM for chunk {chunk_index + 1}: {e}")


def translate_columns_with_llm(columns, llm_client):
    """
    Split columns into chunks of 15 and translate each chunk separately.
    """
    column_names = [col["column"] for col in columns]
    total_count = len(column_names)

    # Chunk size: 15 columns per request (to ensure complete JSON response)
    chunk_size = 15
    chunks = [column_names[i:i + chunk_size] for i in range(0, total_count, chunk_size)]

    print(f"Splitting {total_count} columns into {len(chunks)} chunks of max {chunk_size} items each.")

    full_map = {}
    for i, chunk in enumerate(chunks):
        print(f"Translating chunk {i + 1}/{len(chunks)}...")
        try:
            chunk_map = translate_chunk(chunk, llm_client, i, len(chunks))
            full_map.update(chunk_map)
        except Exception as e:
            print(f"Error translating chunk {i + 1}: {e}")
            # Fallback: use original names for this chunk
            for col in chunk:
                full_map[col] = col

    return full_map


def write_column_map_file(translation_map):
    """
    Write the column_mapper.py file with the full translation dictionary.
    """
    file_path = os.path.join("src", "core", "column_mapper.py")
    os.makedirs(os.path.dirname(file_path), exist_ok=True)

    content = '''# src/core/column_mapper.py
# Auto-generated by scripts/generate_column_map.py
# Do not edit manually. Run the script again to update.

COLUMN_MAP = {
'''
    # Sort keys for better readability
    for key in sorted(translation_map.keys()):
        value = translation_map[key]
        content += f'    "{key}": "{value}",\n'

    content += '''}

def get_column_mapping():
    """Return the full column translation map."""
    return COLUMN_MAP
'''

    with open(file_path, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"Column map file created at: {file_path}")


def main():
    print("Connecting to database...")
    config = load_config()
    db = DatabaseConnection(**config)
    db.connect()

    print("Fetching column list...")
    all_columns = get_all_columns(db.connection)
    db.close()

    if not all_columns:
        print("No columns found. Check database connection and table names.")
        return

    print(f"Found {len(all_columns)} columns across tables.")

    print("Translating with LLM (chunked)...")
    llm = LLMClient()
    translation_map = translate_columns_with_llm(all_columns, llm)

    print(f"Final translation map has {len(translation_map)} items.")

    # Check if all columns are translated
    expected_keys = [col["column"] for col in all_columns]
    missing_keys = [key for key in expected_keys if key not in translation_map]
    if missing_keys:
        print(f"Warning: {len(missing_keys)} columns still missing translations: {missing_keys}")
        print("Filling missing with original names...")
        for key in missing_keys:
            translation_map[key] = key

    print("Writing to column_mapper.py...")
    write_column_map_file(translation_map)

    print("Done. You can now use the full column map in your agent.")


if __name__ == "__main__":
    main()